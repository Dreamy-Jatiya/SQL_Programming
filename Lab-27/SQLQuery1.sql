--1. Create a cursor Employee_Cursor to fetch all rows from EMPLOYEE table and display them.

DECLARE @EID INT,@FNAME VARCHAR(50)

DECLARE EMP_CURSOR CURSOR FOR
SELECT EID,FIRSTNAME
FROM EMPLOYEE

OPEN EMP_CURSOR

FETCH NEXT FROM EMP_CURSOR INTO @EID,@FNAME

WHILE @@FETCH_STATUS=0
BEGIN
    PRINT CAST(@EID AS VARCHAR)+' '+@FNAME

    FETCH NEXT FROM EMP_CURSOR INTO @EID,@FNAME
END

CLOSE EMP_CURSOR
DEALLOCATE EMP_CURSOR


