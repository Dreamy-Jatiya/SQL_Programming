DROP TRIGGER TRG_BLOCK_DELETE;


-- 3. Create INSTEAD OF trigger to log all operations
--    on EMPLOYEE table.

-- INSERT

CREATE TRIGGER TRG_INSERT_LOG
ON EMPLOYEE
INSTEAD OF INSERT
AS
BEGIN
    DECLARE @EID INT;

    SELECT @EID = EID FROM INSERTED;

    INSERT INTO EMPLOYEE_LOG
    (EID, OLDVALUE, NEWVALUE, FIELDNAME, OPERATIONTYPE, LOGDATE)
    VALUES
    (@EID, NULL, 'NEW RECORD', 'EMPLOYEE', 'INSERT', GETDATE());

    INSERT INTO EMPLOYEE
    SELECT * FROM INSERTED;
END;

DROP TRIGGER TRG_INSERT_LOG;


-- UPDATE

