-- Part – A

-- 1. Create INSTEAD OF DELETE trigger to prevent deletion
--    of employee records and store deleted data into EMPLOYEE_LOG table.

CREATE TRIGGER TRG_DELETE
ON EMPLOYEE
INSTEAD OF DELETE
AS
BEGIN
    DECLARE @EID INT, @NAME VARCHAR(100);

    SELECT @EID = EID FROM DELETED;
    SELECT @NAME = FIRSTNAME FROM DELETED;

    INSERT INTO EMPLOYEE_LOG
    (EID, OLDVALUE, NEWVALUE, FIELDNAME, OPERATIONTYPE, LOGDATE)
    VALUES
    (@EID, @NAME, NULL, 'FIRSTNAME', 'DELETE', GETDATE());

    PRINT 'DELETE NOT ALLOWED';
END;

DROP TRIGGER TRG_DELETE;


