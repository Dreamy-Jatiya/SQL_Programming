-- 4. Create trigger to block employees from updating
--    their JOININGYEAR.

CREATE TRIGGER TRG_JOINYEAR
ON EMPLOYEE
INSTEAD OF UPDATE
AS
BEGIN
    IF UPDATE(JOININGYEAR)
    BEGIN
        PRINT 'EMPLOYEES ARE NOT ALLOWED TO UPDATE JOINING YEAR';
    END
    ELSE
    BEGIN
        UPDATE E
        SET FIRSTNAME = I.FIRSTNAME,
            LASTNAME = I.LASTNAME,
            CITY = I.CITY,
            GENDER = I.GENDER,
            DEPARTMENT = I.DEPARTMENT
        FROM EMPLOYEE E
        JOIN INSERTED I
        ON E.EID = I.EID;
    END
END;

DROP TRIGGER TRG_JOINYEAR;


-- 5. Create trigger for preventing duplicate employee
--    records having same FIRSTNAME, LASTNAME and CITY.

CREATE TRIGGER TRG_DUPLICATE
ON EMPLOYEE
INSTEAD OF INSERT
AS
BEGIN
    IF EXISTS
    (
        SELECT *
        FROM EMPLOYEE E
        JOIN INSERTED I
        ON E.FIRSTNAME = I.FIRSTNAME
        AND E.LASTNAME = I.LASTNAME
        AND E.CITY = I.CITY
    )
    BEGIN
        PRINT 'DUPLICATE RECORD NOT ALLOWED';
    END
    ELSE
    BEGIN
        INSERT INTO EMPLOYEE
        SELECT * FROM INSERTED;
    END
END;

DROP TRIGGER TRG_DUPLICATE;


